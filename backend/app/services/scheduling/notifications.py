"""Notification handling for TeleForward scheduling."""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import StrEnum
from typing import Any, Awaitable, Callable, Mapping
from uuid import uuid4

from app.services.scheduling.events import (
    SchedulingEvent,
    SchedulingEventType,
)

logger = logging.getLogger(__name__)


class SchedulingNotificationLevel(StrEnum):
    """Notification severity levels."""

    INFO = "info"
    WARNING = "warning"
    ERROR = "error"


@dataclass(frozen=True, slots=True)
class SchedulingNotification:
    """Structured notification generated by a scheduling event."""

    notification_id: str
    title: str
    message: str
    level: SchedulingNotificationLevel
    event_type: SchedulingEventType
    created_at: datetime
    job_id: str | None = None
    task_name: str | None = None
    execution_id: str | None = None
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        for name in ("notification_id", "title", "message"):
            value = getattr(self, name)
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f"{name} cannot be empty")

        if not isinstance(
            self.level,
            SchedulingNotificationLevel,
        ):
            raise TypeError(
                "level must be a SchedulingNotificationLevel"
            )

        if not isinstance(self.event_type, SchedulingEventType):
            raise TypeError(
                "event_type must be a SchedulingEventType"
            )

        if (
            not isinstance(self.created_at, datetime)
            or self.created_at.tzinfo is None
            or self.created_at.utcoffset() is None
        ):
            raise ValueError(
                "created_at must be timezone-aware"
            )

        if not isinstance(self.metadata, Mapping):
            raise TypeError("metadata must be a mapping")

        object.__setattr__(
            self,
            "metadata",
            dict(self.metadata),
        )


NotificationSender = Callable[
    [SchedulingNotification],
    Awaitable[None],
]


class SchedulingNotificationService:
    """Convert scheduling events and dispatch notifications.

    The sender callback is responsible for actual delivery through
    the application's notification infrastructure.
    """

    _EVENT_MESSAGES: dict[
        SchedulingEventType,
        tuple[str, SchedulingNotificationLevel, str],
    ] = {
        SchedulingEventType.JOB_CREATED: (
            "Scheduled job created",
            SchedulingNotificationLevel.INFO,
            "A scheduled job has been created.",
        ),
        SchedulingEventType.JOB_UPDATED: (
            "Scheduled job updated",
            SchedulingNotificationLevel.INFO,
            "A scheduled job configuration has been updated.",
        ),
        SchedulingEventType.JOB_ENABLED: (
            "Scheduled job enabled",
            SchedulingNotificationLevel.INFO,
            "A scheduled job has been enabled.",
        ),
        SchedulingEventType.JOB_DISABLED: (
            "Scheduled job disabled",
            SchedulingNotificationLevel.WARNING,
            "A scheduled job has been disabled.",
        ),
        SchedulingEventType.JOB_DELETED: (
            "Scheduled job deleted",
            SchedulingNotificationLevel.WARNING,
            "A scheduled job has been deleted.",
        ),
        SchedulingEventType.JOB_RESTORED: (
            "Scheduled job restored",
            SchedulingNotificationLevel.INFO,
            "A scheduled job has been restored.",
        ),
        SchedulingEventType.EXECUTION_STARTED: (
            "Scheduled execution started",
            SchedulingNotificationLevel.INFO,
            "A scheduled task execution has started.",
        ),
        SchedulingEventType.EXECUTION_COMPLETED: (
            "Scheduled execution completed",
            SchedulingNotificationLevel.INFO,
            "A scheduled task execution completed successfully.",
        ),
        SchedulingEventType.EXECUTION_FAILED: (
            "Scheduled execution failed",
            SchedulingNotificationLevel.ERROR,
            "A scheduled task execution failed.",
        ),
        SchedulingEventType.EXECUTION_SKIPPED: (
            "Scheduled execution skipped",
            SchedulingNotificationLevel.WARNING,
            "A scheduled task execution was skipped.",
        ),
        SchedulingEventType.EXECUTION_RETRYING: (
            "Scheduled execution retrying",
            SchedulingNotificationLevel.WARNING,
            "A failed scheduled execution is being retried.",
        ),
        SchedulingEventType.EXECUTION_RETRY_EXHAUSTED: (
            "Scheduled execution retries exhausted",
            SchedulingNotificationLevel.ERROR,
            "All configured execution retries have been exhausted.",
        ),
        SchedulingEventType.SCHEDULER_STARTED: (
            "Scheduler started",
            SchedulingNotificationLevel.INFO,
            "The scheduling service has started.",
        ),
        SchedulingEventType.SCHEDULER_PAUSED: (
            "Scheduler paused",
            SchedulingNotificationLevel.WARNING,
            "The scheduling service has been paused.",
        ),
        SchedulingEventType.SCHEDULER_RESUMED: (
            "Scheduler resumed",
            SchedulingNotificationLevel.INFO,
            "The scheduling service has resumed.",
        ),
        SchedulingEventType.SCHEDULER_STOPPED: (
            "Scheduler stopped",
            SchedulingNotificationLevel.WARNING,
            "The scheduling service has stopped.",
        ),
        SchedulingEventType.RESTORATION_COMPLETED: (
            "Job restoration completed",
            SchedulingNotificationLevel.INFO,
            "Stored scheduled jobs have been restored.",
        ),
        SchedulingEventType.RESTORATION_FAILED: (
            "Job restoration failed",
            SchedulingNotificationLevel.ERROR,
            "One or more stored scheduled jobs could not be restored.",
        ),
    }

    def __init__(
        self,
        *,
        sender: NotificationSender,
        enabled: bool = True,
        enabled_events: set[SchedulingEventType] | None = None,
    ) -> None:
        if not callable(sender):
            raise TypeError("sender must be callable")

        if not isinstance(enabled, bool):
            raise TypeError("enabled must be a boolean")

        if enabled_events is not None:
            if not isinstance(enabled_events, set):
                raise TypeError("enabled_events must be a set")

            if any(
                not isinstance(event_type, SchedulingEventType)
                for event_type in enabled_events
            ):
                raise TypeError(
                    "enabled_events must contain SchedulingEventType values"
                )

        self._sender = sender
        self._enabled = enabled
        self._enabled_events = (
            set(enabled_events)
            if enabled_events is not None
            else set(self._EVENT_MESSAGES)
        )

    @property
    def enabled(self) -> bool:
        """Return whether notification delivery is enabled."""

        return self._enabled

    def set_enabled(self, enabled: bool) -> None:
        """Enable or disable notification delivery."""

        if not isinstance(enabled, bool):
            raise TypeError("enabled must be a boolean")

        self._enabled = enabled

    def set_enabled_events(
        self,
        event_types: set[SchedulingEventType],
    ) -> None:
        """Replace the notification event subscription set."""

        if not isinstance(event_types, set):
            raise TypeError("event_types must be a set")

        if any(
            not isinstance(event_type, SchedulingEventType)
            for event_type in event_types
        ):
            raise TypeError(
                "event_types must contain SchedulingEventType values"
            )

        self._enabled_events = set(event_types)

    def create_notification(
        self,
        event: SchedulingEvent,
    ) -> SchedulingNotification | None:
        """Convert an event into a notification.

        Returns None when the event is not configured for delivery.
        """

        if not isinstance(event, SchedulingEvent):
            raise TypeError("event must be a SchedulingEvent")

        if event.event_type not in self._enabled_events:
            return None

        template = self._EVENT_MESSAGES.get(event.event_type)

        if template is None:
            return None

        title, level, default_message = template

        message_parts = [default_message]

        if event.task_name:
            message_parts.append(f"Task: {event.task_name}")

        if event.job_id:
            message_parts.append(f"Job ID: {event.job_id}")

        if event.execution_id:
            message_parts.append(
                f"Execution ID: {event.execution_id}"
            )

        if event.message:
            message_parts.append(f"Details: {event.message}")

        return SchedulingNotification(
            notification_id=str(uuid4()),
            title=title,
            message="\n".join(message_parts),
            level=level,
            event_type=event.event_type,
            created_at=datetime.now(timezone.utc),
            job_id=event.job_id,
            task_name=event.task_name,
            execution_id=event.execution_id,
            metadata=event.data,
        )

    async def handle_event(
        self,
        event: SchedulingEvent,
    ) -> bool:
        """Convert and dispatch a scheduling event.

        Returns True when a notification was dispatched.
        Returns False when notifications are disabled or the event
        is excluded from the configured event set.

        Delivery errors propagate to the caller.
        """

        if not self._enabled:
            return False

        notification = self.create_notification(event)

        if notification is None:
            return False

        await self._sender(notification)

        logger.info(
            "Scheduling notification dispatched: event=%s job=%s",
            event.event_type.value,
            event.job_id,
        )

        return True
